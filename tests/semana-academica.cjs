// Run against npm run dev or npm run preview. Uses an installed Playwright package.
const assert = require('node:assert/strict')
const playwright = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browserType = playwright[process.env.TEST_BROWSER || 'chromium']
const base = process.env.TEST_BASE_URL || 'http://127.0.0.1:5178/'

async function main() {
  const browser = await browserType.launch({ headless: true, ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {}) })
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  const frame = () => page.frameLocator('iframe[title="Prévia do componente Vue"]')
  const ready = () => page.waitForFunction(() => document.querySelector('.status-dot')?.getAttribute('data-state') === 'ok')
  const failed = () => page.waitForFunction(() => document.querySelector('.status-dot')?.getAttribute('data-state') === 'error')
  async function run(source) {
    await page.getByRole('textbox', { name: 'Código do componente App.vue' }).fill(source)
    await page.getByRole('button', { name: 'Executar' }).click()
  }
  try {
    await page.goto(`${base}#/playground?exemplo=pizza`)
    await ready()
    await frame().getByLabel('Seu nome').fill('Ana')
    await frame().getByLabel('Tamanho da pizza').selectOption('g')
    await frame().getByRole('button', { name: '+', exact: true }).click({ clickCount: 2 })
    assert.match(await frame().locator('.total').innerText(), /135.00/)
    assert.match(await frame().locator('.resumo').innerText(), /Ana/)
    await frame().getByLabel('Calabresa', { exact: true }).check()
    await frame().getByLabel('Calabresa', { exact: true }).uncheck()
    assert.match(await frame().locator('.resumo').innerText(), /Nenhum sabor/)
    for (let i = 0; i < 12; i++) await frame().getByRole('button', { name: '+', exact: true }).click()
    assert.equal(await frame().locator('.quantidade span').innerText(), '10')
    for (let i = 0; i < 12; i++) await frame().getByRole('button', { name: '-', exact: true }).click()
    assert.equal(await frame().locator('.quantidade span').innerText(), '1')
    await frame().getByRole('button', { name: 'Confirmar pedido' }).click()
    assert.match(await frame().getByRole('status').innerText(), /confirmado/)
    console.log('PASS Pizza: campos, sabores, total, limites e confirmação')

    await page.getByLabel('Exemplo', { exact: true }).selectOption('todo-crud')
    await page.getByRole('button', { name: 'Executar' }).click()
    await ready()
    await frame().getByLabel('Título da tarefa').fill('   ')
    await frame().getByRole('button', { name: 'Salvar', exact: true }).click()
    assert.equal(await frame().getByRole('alert').count(), 2)
    async function add(title, description) {
      await frame().getByLabel('Título da tarefa').fill(title)
      await frame().getByLabel('Descrição', { exact: true }).fill(description)
      await frame().getByRole('button', { name: 'Salvar', exact: true }).click()
    }
    await add('Primeira', 'Descrição um')
    await add('Segunda', 'Descrição dois')
    await frame().locator('article').nth(1).getByRole('button', { name: 'Editar', exact: true }).click()
    await frame().getByLabel('Título da tarefa').fill('Segunda editada')
    assert.equal(await frame().locator('article').nth(1).locator('h3').innerText(), 'Segunda')
    await frame().locator('article').first().getByRole('button', { name: 'Excluir', exact: true }).click()
    await frame().getByRole('button', { name: 'Confirmar exclusão' }).click()
    await frame().getByRole('button', { name: 'Salvar alteração' }).click()
    assert.equal(await frame().locator('article h3').innerText(), 'Segunda editada')
    await frame().getByRole('button', { name: 'Excluir', exact: true }).click()
    await frame().getByRole('button', { name: 'Cancelar', exact: true }).click()
    assert.equal(await frame().locator('article').count(), 1)
    console.log('PASS TodoList: validação, cadastro, cópia, exclusão, edição após deslocar índice e cancelamento')

    for (const id of ['contador', 'tarefas', 'saudacao', 'formulario']) {
      await page.getByLabel('Exemplo', { exact: true }).selectOption(id)
      await page.getByRole('button', { name: 'Executar' }).click()
      await ready()
    }
    await run('<template><h1>Somente template</h1></template><style>body { background: rgb(255, 0, 0); }</style>')
    await ready()
    assert.equal(await frame().locator('h1').innerText(), 'Somente template')
    assert.notEqual(await page.locator('body').evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(255, 0, 0)')
    await run('<script>export default { data() { return { n: 7 } } }</script><template><p>{{ n }}</p></template>')
    await ready()
    assert.equal(await frame().locator('#app p').innerText(), '7')
    await run('<script setup lang="ts">import { ref } from "vue"; const n = ref<number>(8)</script><template><p>{{ n }}</p></template>')
    await ready()
    assert.equal(await frame().locator('#app p').innerText(), '8')
    await run('<template><div></template>')
    await failed()
    assert.match(await page.locator('.error').innerText(), /Erro|interpretar/)
    assert.equal(await frame().locator('#app p').innerText(), '8')
    await run('<script setup>throw new Error("falha controlada")</script><template><p>erro</p></template>')
    await failed()
    assert.match(await page.locator('.error').innerText(), /falha controlada/)
    await run('<script setup>import x from "./Outro.vue"</script><template><p>x</p></template>')
    await failed()
    assert.match(await page.locator('.error').innerText(), /único arquivo|Imports/)
    await run('<script setup>const titulo = parent.document.title</script><template><p>{{ titulo }}</p></template>')
    await failed()
    assert.match(await page.locator('.error').innerText(), /Blocked|cross-origin|denied/i)
    await page.getByRole('button', { name: 'Restaurar exemplo' }).click()
    await ready()
    await page.getByRole('textbox', { name: 'Código do componente App.vue' }).focus()
    await page.keyboard.press('Escape')
    await page.keyboard.press('Tab')
    assert.equal(await page.getByRole('textbox', { name: 'Código do componente App.vue' }).evaluate(el => el === document.activeElement), false)
    console.log('PASS playground: 6 exemplos, TS, Options API, template, CSS isolado, erros/recuperação, isolamento do site e teclado')

    await page.goto(`${base}#/atividades`)
    await page.getByRole('heading', { name: 'Atividades práticas' }).waitFor()
    await page.getByLabel('Filtrar por aula', { exact: true }).selectOption('02')
    assert.equal(await page.locator('.cards article').count(), 3)
    await page.getByRole('link', { name: 'TodoList · componentes, Bootstrap e Git', exact: true }).click()
    await page.getByRole('button', { name: 'Marcar como concluído' }).click()
    await page.reload()
    await page.getByRole('button', { name: 'Marcar como pendente' }).waitFor()
    await page.goto(`${base}#/desafios`)
    await page.getByRole('heading', { name: 'Desafios de programação', exact: true }).waitFor()
    assert.equal(await page.locator('.cards article').count(), 3)
    assert.equal(await page.getByRole('link', { name: 'Pizza Vue + Git · revisão oficial' }).count(), 0)
    await page.goto(`${base}#/cursos/vue-github/desafios/pizza-vue-git-oficial`)
    await page.getByRole('heading', { name: 'Página não encontrada' }).waitFor()
    await page.goto(`${base}#/cursos/vue-github/encontros/02`)
    await page.getByRole('heading', { name: 'TodoList · Vue, Bootstrap e versionamento', exact: true }).waitFor()
    assert.match(await page.locator('body').innerText(), /160 min/)
    for (const file of ['roteiro-aula-01-teoria.pdf', 'projeto-aula-01.pdf', 'projeto-aula-02.pdf', 'pratica-aula-02.pdf']) {
      const response = await page.request.get(`${base}materiais/vue-github/oficiais/${file}`)
      assert.equal(response.status(), 200)
      assert.equal((await response.body()).subarray(0, 4).toString(), '%PDF')
    }
    await page.evaluate(() => localStorage.setItem('devlab-progress-v1', '{broken'))
    await page.goto(`${base}#/atividades`)
    await page.reload()
    await page.getByRole('heading', { name: 'Atividades práticas' }).waitFor()
    const blocked = await browser.newContext()
    await blocked.addInitScript(() => { Object.defineProperty(window, 'localStorage', { get() { throw new Error('blocked') } }) })
    const blockedPage = await blocked.newPage()
    await blockedPage.goto(`${base}#/cursos/vue-github/exercicios/pizza-vue`)
    await blockedPage.getByRole('button', { name: 'Marcar como concluído' }).click()
    await blockedPage.getByRole('button', { name: 'Marcar como pendente' }).waitFor()
    assert.match(await blockedPage.locator('.practice-actions').innerText(), /apenas nesta sessão/)
    await blocked.close()
    console.log('PASS catálogo: filtros, progresso/reload, armazenamento inválido/bloqueado, desafios, quiz oficial removido e 4 PDFs')

    for (const width of [1440, 390]) {
      await page.setViewportSize({ width, height: 900 })
      for (const route of ['', 'atividades', 'desafios', 'playground?exemplo=pizza']) {
        await page.goto(`${base}#/${route}`)
        await page.locator('h1').first().waitFor()
        if (route.startsWith('playground')) await ready()
        assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), `overflow ${width} ${route}`)
        if (process.env.SCREENSHOT_DIR) await page.screenshot({ path: `${process.env.SCREENSHOT_DIR}/${width}-${route.split('?')[0] || 'home'}.png`, fullPage: true })
      }
    }
    assert.deepEqual(errors, [])
    console.log('PASS desktop/mobile: 8 telas sem overflow; nenhum pageerror no site')
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
